"""Package the approved native Aseprite Hermit Crab frames without repainting.

Source: docs/previews/hermit-crab/author.lua and its exported PNG/TSV files.
The item icon is independent and is deliberately preserved. The emitted Lua
attachment table is the runtime source of truth for feet, slots and scale, and
for each trinket icon's opaque bounds: measured here from the extracted vanilla
icons and this mod's own, because Sprite:GetTexel reads alpha 0 everywhere in
game (measured 2026-11-09), so the runtime cannot measure them itself. Only the
numbers are emitted, never the vanilla pixels.
Run the Aseprite author after art changes, then this script. --check is read-only.
"""
from pathlib import Path
import argparse
import csv
import xml.etree.ElementTree as ET
from PIL import Image

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / 'docs/previews/hermit-crab'
TRINKET_ICONS = [ROOT.parent.parent / 'extracted_resources/resources/gfx/items/trinkets',
                 ROOT / 'resources/gfx/items/trinkets']
CELL, DELAY = 48, 3  # eight steps at 30 FPS / three ticks = 0.8 second
POSES = [('shell-base', 'NormalEmpty'), ('carry-one', 'NormalOne'),
         ('bffs-empty', 'BffsEmpty'), ('bffs-one', 'BffsOne'), ('bffs-claws', 'BffsTwo')]
ATTR = dict(XPosition='0', YPosition='0', XScale='100', YScale='100',
            RedTint='255', GreenTint='255', BlueTint='255', AlphaTint='255',
            RedOffset='0', GreenOffset='0', BlueOffset='0', Rotation='0', Interpolated='false')


def frame(parent, **kwargs):
    return ET.SubElement(parent, 'Frame', {**ATTR, **{k: str(v) for k, v in kwargs.items()}})


def animation(parent, name, layer, rows, walk, pivot, trinket=False):
    delay = DELAY if walk else 1
    selected = rows if walk else rows[:1]
    duration = delay * len(selected)
    a = ET.SubElement(parent, 'Animation', Name=name, FrameNum=str(duration), Loop='true')
    frame(ET.SubElement(a, 'RootAnimation'), Delay=duration, Visible='true')
    ls = ET.SubElement(a, 'LayerAnimations')
    l = ET.SubElement(ls, 'LayerAnimation', LayerId=str(layer), Visible='true')
    for row in selected:
        frame(l, XPivot=pivot[0], YPivot=pivot[1], XCrop=0 if trinket else row['cell_x'],
              YCrop=0 if trinket else row['cell_y'], Width=32 if trinket else CELL,
              Height=32 if trinket else CELL, Delay=delay, Visible='true')
    ET.SubElement(a, 'NullAnimations')
    ET.SubElement(a, 'Triggers')


def trinket_bounds():
    """{lower-case file name: (centre x, top, bottom)} of every 32x32 trinket icon."""
    bounds = {}
    for folder in TRINKET_ICONS:
        assert folder.is_dir(), f'missing trinket icons (re-extract the game resources): {folder}'
        for png in sorted(folder.glob('*.png')):
            with Image.open(png) as im:
                if im.size != (32, 32):
                    continue
                box = im.convert('RGBA').getchannel('A').getbbox()
            if box:
                bounds[png.name.lower()] = ((box[0] + box[2]) / 2, box[1], box[3])
    return bounds


def median(values):
    values = sorted(values)
    middle = len(values) // 2
    return values[middle] if len(values) % 2 else (values[middle - 1] + values[middle]) / 2


def build_outputs():
    with (SOURCE / 'attachments.tsv').open(encoding='utf-8') as source:
        rows = list(csv.DictReader(source, delimiter='\t'))
    assert len(rows) == 40 and {r['direction'] for r in rows} == {'front'}
    for file in ('directions_sheet.png', 'grip_sheet.png'):
        with Image.open(SOURCE / file) as im:
            assert im.size == (384, 240)
            assert set(im.convert('RGBA').getchannel('A').get_flattened_data()) == {0, 255}
    actor = ET.Element('AnimatedActor')
    ET.SubElement(actor, 'Info', CreatedBy='generate_hermit_crab_assets.py', Fps='30', Version='1')
    content = ET.SubElement(actor, 'Content')
    sheets = ET.SubElement(content, 'Spritesheets')
    ET.SubElement(sheets, 'Spritesheet', Path='familiar/familiar_hermit_crab.png', Id='0')
    ET.SubElement(sheets, 'Spritesheet', Path='familiar/familiar_hermit_crab_grip.png', Id='1')
    layers = ET.SubElement(content, 'Layers')
    ET.SubElement(layers, 'Layer', Name='body or separate original trinket', Id='0', SpritesheetId='0')
    ET.SubElement(layers, 'Layer', Name='foreground fingertips', Id='1', SpritesheetId='1')
    ET.SubElement(content, 'Nulls'); ET.SubElement(content, 'Events')
    anims = ET.SubElement(actor, 'Animations', DefaultAnimation='NormalEmptyIdle')
    lua = ['-- Generated by generate_hermit_crab_assets.py from the native Aseprite exports.',
           '-- Do not hand-edit attachment coordinates or add a second BFFS scaling pass.',
           'return {', f'    frameDelay = {DELAY},', '    stepCount = 8,', '    poses = {']
    for mode, pose in POSES:
        group = sorted((r for r in rows if r['mode'] == mode), key=lambda r: int(r['step']))
        assert [int(r['step']) for r in group] == list(range(8))
        size = int(group[0]['size']); offset = (8, 12) if size == 32 else (0, 0)
        pivot = (24, 42) if size == 32 else (24, 45)
        for walk, suffix in ((False, 'Idle'), (True, 'Walk')):
            animation(anims, pose + suffix, 0, group, walk, pivot)
            animation(anims, 'Grip' + pose + suffix, 1, group, walk, pivot)
        lua.append(f'        {pose} = {{ frames = {{')
        for r in group:
            slots = []
            for i in (1, 2):
                if not r[f'slot{i}_x']:
                    continue
                x = float(r[f'slot{i}_x']) + offset[0] - pivot[0]
                y = float(r[f'slot{i}_bottom']) + offset[1] - pivot[1]
                scale = float(r[f'slot{i}_scale'])
                assert scale == (0.5625 if size == 32 else 0.75)
                clearance = ''
                if r.get(f'slot{i}_min_top'):
                    top = float(r[f'slot{i}_min_top']) + offset[1] - pivot[1]
                    clearance = f', minTop = {top:g}'
                slots.append(f'{{ x = {x:g}, bottom = {y:g}, scale = {scale:g}{clearance} }}')
            lua.append('            { ' + ', '.join(slots) + ' },')
        lua.append('        } },')
    lua.append('    },')
    bounds = trinket_bounds()
    vanilla = [b for name, b in bounds.items() if name.startswith('trinket_')]
    # another mod's trinket is not measured: assume the typical vanilla box
    lua.append(f'    defaultBounds = {{ 16, {median([b[1] for b in vanilla]):g}, {median([b[2] for b in vanilla]):g} }},')
    lua.append('    -- { centre x, top, bottom } of each 32x32 icon, by lower-case file name')
    lua.append('    trinketBounds = {')
    for name in sorted(bounds):
        c, t, b = bounds[name]
        lua.append(f'        ["{name}"] = {{ {c:g}, {t}, {b} }},')
    lua += ['    },', '}', '']
    # The icon sprite replaces sheet 0 independently of the familiar's sprite.
    # A zero pivot also makes guarded GetTexel sampling use raw image coordinates.
    animation(anims, 'Trinket', 0, rows[:1], False, (0, 0), trinket=True)
    ET.indent(actor, space='  ')
    return {
        ROOT / 'resources/gfx/familiar/familiar_hermit_crab.png': (SOURCE / 'directions_sheet.png').read_bytes(),
        ROOT / 'resources/gfx/familiar/familiar_hermit_crab_grip.png': (SOURCE / 'grip_sheet.png').read_bytes(),
        ROOT / 'resources/gfx/hermit_crab.anm2': ET.tostring(actor, encoding='utf-8') + b'\n',
        ROOT / 'scripts/items/familiars/hermit_crab_visuals.lua': '\n'.join(lua).encode('utf-8'),
    }


def main():
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    outputs = build_outputs()
    for path, data in outputs.items():
        if args.check:
            assert path.read_bytes() == data, f'outdated generated asset: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True); path.write_bytes(data)
    print(('Checked' if args.check else 'Packaged') + ' approved Hermit Crab body/grip sheets, animations and attachment data')


if __name__ == '__main__':
    main()
