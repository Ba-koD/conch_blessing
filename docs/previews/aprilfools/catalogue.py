"""Generate the runtime allowlist and an exhaustive authored-image audit."""
import json
from pathlib import Path
from build import ROOT,OUT

# Not physical objects. These are implementation masks, light falloff, fonts,
# or retired source sheets; re-modelling them would change unrelated behaviour.
EXCEPTIONS={
 'gfx/ui/null.png':'transparent UI control',
 'gfx/characters/costumes/conch_neglect_toggle.png':'transparent wardrobe control',
 'gfx/effects/conch_upgrade_pixel.png':'1px drawing primitive, tint/scale supplied by renderer',
 'gfx/effects/conch_upgrade_spotlight.png':'light falloff, not a physical object',
 'gfx/font/Kkubulim_0.png':'font atlas; preserve text readability',
 'gfx/effects/conch_ox.png':'retired sheet; runtime conch_ox.anm2 uses directions/equipped sleep',
 'gfx/effects/conch_ox_sleep.png':'retired sheet; runtime uses conch_ox_sleep_equipped',
 'gfx/items/collectibles/tmp.png':'unused template',
 'gfx/items/trinkets/tmp.png':'unused template',
 'gfx/items/trinkets/time_template.png':'unused template',
 # 선녀 (2026-11-13): its art is new and not yet modelled; until it is, April
 # Fools keeps the original. Remove these two when the model is authored.
 'gfx/items/collectibles/seonnyeo.png':'new item, 3D model pending: original kept',
 'gfx/familiar/familiar_seonnyeo.png':'new item, 3D model pending: original kept',
}


def main():
    rows=[]
    for name in ['items','actors','extras']:
        rows+=json.loads((OUT/f'{name}.json').read_text(encoding='utf-8'))
    mapping={r['source'].lower():r for r in rows}
    lines=['-- Generated by docs/previews/aprilfools/catalogue.py; do not hand edit.','return {']
    for source,r in sorted(mapping.items()):
        fields=[f'still = "{r["still"]}"']
        if 'spin' in r:fields += [f'spin = "{r["spin"]}"',f'frames = {r["frames"]}',f'delay = {r["delay"]}']
        lines.append('    ["'+source+'"] = { '+', '.join(fields)+' },')
    lines+=['}','']
    (ROOT/'scripts/lib/april_fools_assets.lua').write_text('\n'.join(lines),encoding='utf-8')
    audit=[];missing=[]
    for p in sorted((ROOT/'resources/gfx').rglob('*.png')):
        if 'notused' in p.parts or '_af3d' in p.stem:continue
        relative=p.relative_to(ROOT/'resources').as_posix()
        row=mapping.get(relative.lower())
        if row:status='modelled';detail=row['still']
        elif relative in EXCEPTIONS:status='preserved';detail=EXCEPTIONS[relative]
        else:status='MISSING';detail='';missing.append(relative)
        audit.append({'source':relative,'status':status,'detail':detail})
    (OUT/'coverage.json').write_text(json.dumps(audit,indent=2)+'\n',encoding='utf-8')
    print(len(mapping),'mapped sheets;',len(audit),'source images;',len(missing),'unaccounted')
    if missing:raise SystemExit('\n'.join(missing))


if __name__=='__main__':main()
